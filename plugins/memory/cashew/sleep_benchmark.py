"""Deterministic, opt-in measurements for the pinned sleep adapter.

This module is deliberately diagnostic.  It runs the pinned upstream sleep
cycle through the Hermes adapter against a temporary SQLite database and
reports the work selected by each phase, phase wall time, edge-cap commit
integrity, and writer contention.  It does not change the production sleep
pipeline or provide a second consolidation engine.

The benchmark records the current bounded sleep contract at the adapter
boundary.  It can be rerun after a dependency or adapter change to compare
measurements at the same fixture sizes.
"""

from __future__ import annotations

import contextlib
import json
import math
import pathlib
import sqlite3
import tempfile
import threading
import time
from collections.abc import Callable, Iterator
from typing import Any

import numpy as np
from core import sleep as upstream_sleep

from . import sleep_adapter
from .locking import try_shared_lock

EMBEDDING_MODEL = "thenlper/gte-large"
DEFAULT_DIMENSION = 1024


class _SlowEmbeddingClient:
    """Deterministic embedding client with a synchronization hook."""

    def __init__(self, dimension: int, delay_s: float) -> None:
        self.dimension = dimension
        self.delay_s = delay_s
        self.started = threading.Event()
        self.calls = 0

    def encode(self, texts: list[str]) -> np.ndarray:
        self.calls += 1
        self.started.set()
        if self.delay_s:
            time.sleep(self.delay_s)
        vectors = []
        for text in texts:
            # Hashing is intentionally avoided: Python's hash seed is process
            # random.  The content is generated by this module, so its first
            # integer is stable and sufficient for a deterministic vector.
            index = int(text.rsplit(" ", 1)[-1]) % self.dimension
            vector = np.zeros(self.dimension, dtype=np.float32)
            vector[index] = 1.0
            vectors.append(vector)
        return np.asarray(vectors, dtype=np.float32)


def _create_schema(conn: sqlite3.Connection) -> None:
    """Create the subset of the Cashew schema used by the local adapter."""
    conn.executescript(
        """
        CREATE TABLE thought_nodes (
            id TEXT PRIMARY KEY,
            content TEXT NOT NULL,
            node_type TEXT NOT NULL DEFAULT 'observation',
            timestamp TEXT NOT NULL,
            mood_state TEXT,
            metadata TEXT,
            source_file TEXT,
            decayed INTEGER DEFAULT 0,
            permanent INTEGER DEFAULT 0,
            domain TEXT DEFAULT 'benchmark',
            access_count INTEGER DEFAULT 0,
            last_accessed TEXT,
            tags TEXT
        );
        CREATE TABLE derivation_edges (
            parent_id TEXT NOT NULL,
            child_id TEXT NOT NULL,
            weight REAL NOT NULL DEFAULT 1.0,
            reasoning TEXT
        );
        CREATE INDEX idx_benchmark_edges_parent ON derivation_edges(parent_id);
        CREATE INDEX idx_benchmark_edges_child ON derivation_edges(child_id);
        CREATE TABLE embeddings (
            node_id TEXT PRIMARY KEY,
            vector BLOB NOT NULL,
            model TEXT NOT NULL,
            updated_at TEXT NOT NULL
        );
        """
    )
    # sqlite-vec is a required runtime dependency, but retaining the ordinary
    # table path makes this diagnostic useful on platforms where its native
    # extension cannot load.  The upstream cycle will then report the
    # degraded vector capability in its normal result fields.
    try:
        import sqlite_vec

        conn.enable_load_extension(True)
        sqlite_vec.load(conn)
        conn.execute(
            "CREATE VIRTUAL TABLE vec_embeddings USING vec0("
            f"node_id TEXT PRIMARY KEY, embedding float[{DEFAULT_DIMENSION}] "
            "distance_metric=cosine)"
        )
        conn.enable_load_extension(False)
    except Exception:
        conn.enable_load_extension(False)


def _seed_database(
    db_path: pathlib.Path,
    *,
    node_count: int,
    orphan_count: int,
    dimension: int,
    pair_similarity: float | None,
) -> None:
    if node_count < 2:
        raise ValueError("node_count must be at least 2")
    if orphan_count < 0:
        raise ValueError("orphan_count must be non-negative")
    if dimension < 2:
        raise ValueError("dimension must be at least 2")
    if pair_similarity is not None and not 0.0 <= pair_similarity < 1.0:
        raise ValueError("pair_similarity must be in [0, 1)")

    conn = sqlite3.connect(db_path)
    try:
        _create_schema(conn)
        for index in range(node_count):
            node_id = f"node-{index}"
            conn.execute(
                "INSERT INTO thought_nodes "
                "(id, content, timestamp, source_file) VALUES (?, ?, ?, ?)",
                (node_id, f"benchmark node {index}", "2020-01-01T00:00:00", ""),
            )
            if pair_similarity is None:
                vector = np.zeros(dimension, dtype=np.float32)
                vector[index % dimension] = 1.0
            else:
                vector = np.zeros(dimension, dtype=np.float32)
                vector[0] = np.sqrt(pair_similarity)
                vector[index + 1] = np.sqrt(1.0 - pair_similarity)
            conn.execute(
                "INSERT INTO embeddings (node_id, vector, model, updated_at) "
                "VALUES (?, ?, ?, ?)",
                (node_id, vector.tobytes(), "benchmark", "2020-01-01T00:00:00"),
            )
        for index in range(orphan_count):
            conn.execute(
                "INSERT INTO thought_nodes "
                "(id, content, timestamp, source_file) VALUES (?, ?, ?, ?)",
                (
                    f"orphan-{index}",
                    f"benchmark orphan {index}",
                    "2020-01-01T00:00:00",
                    "",
                ),
            )
            # Keep the synthetic orphan eligible for the embedding phase: the
            # local GC phase runs before orphan repair and would otherwise
            # decay isolated zero-fitness fixtures.
            conn.execute(
                "INSERT INTO derivation_edges "
                "(parent_id, child_id, weight, reasoning) VALUES (?, ?, ?, ?)",
                (f"orphan-{index}", "node-0", 1.0, "benchmark-anchor"),
            )
        conn.commit()
    finally:
        conn.close()


@contextlib.contextmanager
def _timed_phases(
    event: threading.Event,
    timings: dict[str, float],
    lock_probe_complete: threading.Event,
) -> Iterator[None]:
    """Instrument the existing phase functions for one benchmark call."""
    names = (
        "_find_pairs",
        "_batch_cross_links",
        "_run_dedup",
        "_compute_metrics",
        "_garbage_collect",
        "_evaluate_permanence",
        "_promote_core_memories",
        "_embed_orphans",
    )
    originals: dict[str, Callable[..., Any]] = {}
    for name in names:
        timings.setdefault(name.removeprefix("_"), 0.0)

    def wrap(name: str, original: Callable[..., Any]) -> Callable[..., Any]:
        def measured(*args: Any, **kwargs: Any) -> Any:
            start = time.perf_counter()
            if name == "_find_pairs":
                event.set()
                # Do not let a fast candidate pass release the maintenance
                # lease before the competing participant has sampled it.
                lock_probe_complete.wait(timeout=5.0)
            try:
                return original(*args, **kwargs)
            finally:
                timings[name.removeprefix("_")] = round(
                    (time.perf_counter() - start) * 1000, 3
                )

        return measured

    try:
        for name in names:
            original = getattr(upstream_sleep, name)
            originals[name] = original
            setattr(upstream_sleep, name, wrap(name, original))
        yield
    finally:
        for name, original in originals.items():
            setattr(upstream_sleep, name, original)


def _measure_sleep_cycle(
    db_path: pathlib.Path,
    *,
    node_count: int,
    orphan_count: int,
    delay_s: float = 0.05,
    limit: int | None = None,
    max_edges: int = 100_000,
    pair_similarity: float | None = None,
    dimension: int = DEFAULT_DIMENSION,
) -> dict[str, Any]:
    """Run one deterministic cycle and return JSON-safe measurements.

    ``pair_similarity=0.92`` creates cross-link candidates without dedup
    candidates and is useful for exercising the edge cap.  The default uses
    orthogonal vectors, isolating phase and contention costs.
    """
    if not math.isfinite(delay_s) or delay_s < 0:
        raise ValueError("delay_s must be a finite non-negative number")
    effective_limit = node_count if limit is None else limit
    if effective_limit < 2:
        raise ValueError("limit must be at least 2")
    if max_edges < 0:
        raise ValueError("max_edges must be non-negative")
    effective_dimension = dimension
    if effective_dimension != DEFAULT_DIMENSION:
        raise ValueError(
            f"dimension must be the calibrated {DEFAULT_DIMENSION}-dimensional "
            f"{EMBEDDING_MODEL} profile"
        )
    _seed_database(
        db_path,
        node_count=node_count,
        orphan_count=orphan_count,
        dimension=effective_dimension,
        pair_similarity=pair_similarity,
    )

    client = _SlowEmbeddingClient(effective_dimension, delay_s)
    phase_started = threading.Event()
    lock_probe_complete = threading.Event()
    timings: dict[str, float] = {}
    writer_result: dict[str, Any] = {}

    def participating_writer() -> None:
        if not phase_started.wait(timeout=5.0):
            writer_result.update({"observed": False})
            lock_probe_complete.set()
            return
        started = time.perf_counter()
        try:
            with try_shared_lock(db_path) as lease:
                writer_result.update(
                    {
                        "observed": True,
                        "admitted": lease is not None,
                        "elapsed_ms": round(
                            (time.perf_counter() - started) * 1000, 3
                        ),
                    }
                )
        except OSError as exc:
            writer_result.update(
                {"observed": True, "error": type(exc).__name__}
            )
        finally:
            lock_probe_complete.set()

    def sqlite_writer() -> None:
        if not client.started.wait(timeout=5.0):
            writer_result["sqlite_writer_error"] = "embedding did not start"
            return
        started = time.perf_counter()
        conn = sqlite3.connect(db_path, timeout=5.0)
        try:
            conn.execute(
                "INSERT INTO thought_nodes "
                "(id, content, timestamp, source_file) VALUES (?, ?, ?, ?)",
                ("concurrent-writer", "writer probe", "2020-01-01T00:00:00", ""),
            )
            conn.commit()
            writer_result["sqlite_writer_commit_ms"] = round(
                (time.perf_counter() - started) * 1000, 3
            )
        except Exception as exc:
            writer_result["sqlite_writer_error"] = type(exc).__name__
        finally:
            conn.close()

    lock_thread = threading.Thread(target=participating_writer, daemon=True)
    sqlite_thread = threading.Thread(target=sqlite_writer, daemon=True)
    lock_thread.start()
    if orphan_count:
        sqlite_thread.start()
    cycle_started = time.perf_counter()
    with _timed_phases(phase_started, timings, lock_probe_complete):
        summary = sleep_adapter.run_sleep_cycle(
            str(db_path),
            limit=effective_limit,
            max_edges=max_edges,
            model_fn=None,
            background_dream=False,
            embedding_model=EMBEDDING_MODEL,
            embedding_device="cpu",
            embedding_client=client,
        )
    cycle_elapsed_ms = round((time.perf_counter() - cycle_started) * 1000, 3)
    lock_thread.join(timeout=5.0)
    if orphan_count:
        sqlite_thread.join(timeout=5.0)

    conn = sqlite3.connect(db_path)
    try:
        edge_rows = int(conn.execute("SELECT COUNT(*) FROM derivation_edges").fetchone()[0])
        cross_link_rows = int(
            conn.execute(
                "SELECT COUNT(*) FROM derivation_edges "
                "WHERE reasoning LIKE 'cross_link%'")
            .fetchone()[0]
        )
        orphan_rows = int(
            conn.execute(
                "SELECT COUNT(*) FROM thought_nodes tn "
                "LEFT JOIN embeddings e ON e.node_id = tn.id "
                "WHERE tn.id LIKE 'orphan-%' AND e.node_id IS NOT NULL"
            ).fetchone()[0]
        )
        total_nodes = int(conn.execute("SELECT COUNT(*) FROM thought_nodes").fetchone()[0])
    finally:
        conn.close()

    return {
        "fixture": {
            "nodes": node_count,
            "orphans": orphan_count,
            "delay_ms": round(delay_s * 1000, 3),
            "limit": effective_limit,
            "max_edges": max_edges,
            "pair_similarity": pair_similarity,
        },
        "cycle_elapsed_ms": cycle_elapsed_ms,
        "phase_ms": timings,
        "summary": summary,
        "embedding_calls": client.calls,
        "orphan_rows_with_embeddings": orphan_rows,
        "edge_rows": edge_rows,
        "cross_link_rows": cross_link_rows,
        "total_nodes": total_nodes,
        "participating_writer": writer_result,
        "bounded_integrity": (
            int(summary.get("cross_links_created", 0)) * 2 == cross_link_rows
            and int(summary.get("orphans_embedded", 0)) == orphan_rows
        ),
    }


def run_benchmark(
    *,
    node_count: int,
    orphan_count: int,
    delay_s: float = 0.05,
    limit: int | None = None,
    max_edges: int = 100_000,
    pair_similarity: float | None = None,
    dimension: int = DEFAULT_DIMENSION,
) -> dict[str, Any]:
    """Run a benchmark in temporary storage owned by this function.

    The public API intentionally has no database-path argument.  Benchmark
    callers cannot point the probe at a live Hermes profile or user database.
    """
    with tempfile.TemporaryDirectory(prefix="hermes-cashew-sleep-") as temp_dir:
        return _measure_sleep_cycle(
            pathlib.Path(temp_dir) / "brain.db",
            node_count=node_count,
            orphan_count=orphan_count,
            delay_s=delay_s,
            limit=limit,
            max_edges=max_edges,
            pair_similarity=pair_similarity,
            dimension=dimension,
        )


def main() -> None:
    """Run a small opt-in probe from the command line."""
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nodes", type=int, nargs="+", default=[32, 128])
    parser.add_argument("--orphans", type=int, default=4)
    parser.add_argument("--delay-ms", type=float, default=50.0)
    parser.add_argument("--limit", type=int)
    parser.add_argument("--max-edges", type=int, default=100_000)
    parser.add_argument("--pair-similarity", type=float)
    args = parser.parse_args()
    results = [
        run_benchmark(
            node_count=nodes,
            orphan_count=args.orphans,
            delay_s=args.delay_ms / 1000,
            limit=args.limit,
            max_edges=args.max_edges,
            pair_similarity=args.pair_similarity,
        )
        for nodes in args.nodes
    ]
    print(json.dumps(results, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
